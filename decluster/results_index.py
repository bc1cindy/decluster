"""Build the index of `results/`, so which documents carry a chain is readable rather than guessed.

Sixty-six hand-written documents and fifty-seven generated ones sit in one directory with no entry
point. A reader cannot tell, without opening each, which are regenerated from a canonical run and
which are prose over data the repository does not ship — and that distinction is the whole
difference between a figure someone can check and one they have to take.

The index is generated, so it cannot drift from the catalogue the way a hand-written list would.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

INDEX = "results/INDEX.md"


def _runs(root):
    """Which run manifest owns each generated document, and which claims it discharges."""
    owners = {}
    for path in sorted(Path(root, "catalog", "runs").glob("*.json")):
        manifest = json.loads(path.read_text())
        for output in manifest["outputs"]:
            if output["path"].endswith(".md"):
                owners[output["path"]] = (path.stem, tuple(manifest["claim_ids"]))
    return owners


def _legacy(root):
    return {path.stem + ".md" for path in Path(root, "results", "manifests").glob("*.json")}


def _title(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def build(root="."):
    root = Path(root)
    owners = _runs(root)
    legacy = _legacy(root)
    generated = sorted(Path(root, "results", "generated").glob("*.md"))
    manual = sorted(Path(root, "results").glob("RESULTS-*.md"))

    lines = [
        "# What is in `results/`",
        "",
        "Generated by `decluster.results_index`. Do not edit manually.",
        "",
        f"{len(generated)} generated documents, each the canonical rendering of a run manifest, and "
        f"{len(manual)} written ones. The difference is what a reader can check: a generated "
        "document is reproduced byte-for-byte by its run and verified by the reproduction gate, "
        "while a written one is prose that may rest on data this repository does not ship.",
        "",
        "## Generated from a canonical run",
        "",
        "| document | run | claims |",
        "|---|---|---|",
    ]
    for path in generated:
        key = f"results/generated/{path.name}"
        run, claims = owners.get(key, ("—", ()))
        lines.append(f"| [`{path.name}`]({path.name and 'generated/' + path.name}) | `{run}` | "
                     f"{', '.join(f'`{c}`' for c in claims) or '—'} |")

    lines += [
        "",
        "## Written, with a legacy manifest",
        "",
        "These carry a `results/manifests/` fingerprint of the source they were measured on, so a "
        "moved source is detected even though the numbers are not regenerated.",
        "",
        "| document | title |",
        "|---|---|",
    ]
    for path in manual:
        if path.name in legacy:
            lines.append(f"| [`{path.name}`]({path.name}) | {_title(path)} |")

    lines += [
        "",
        "## Written, no manifest",
        "",
        "Prose over measurements whose source is named in the document itself. Several rest on "
        "exports this repository does not ship; each says so where that is the case.",
        "",
        "| document | title |",
        "|---|---|",
    ]
    for path in manual:
        if path.name not in legacy:
            lines.append(f"| [`{path.name}`]({path.name}) | {_title(path)} |")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".")
    parser.add_argument("--check", action="store_true",
                        help="report drift instead of writing")
    arguments = parser.parse_args(argv)
    rendered = build(arguments.root)
    destination = Path(arguments.root, INDEX)
    if arguments.check:
        current = destination.read_text(encoding="utf-8") if destination.is_file() else ""
        if current != rendered:
            print(f"{INDEX} differs from the catalogue")
            return 1
        return 0
    destination.write_text(rendered, encoding="utf-8")
    print(f"{INDEX}  {len(rendered.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
